/* ------------------------------------------------------------------ *
 * §2.2 — POST /api/analogy
 * ------------------------------------------------------------------ */

/**
 * The four built-in themes. Each has a hand-authored ROLE_VOCAB map in lib/analogyPrompts.ts,
 * which is what makes their analogies sharper than a one-shot prompt can manage.
 */
export type PresetAnalogyType = "restaurant" | "airport" | "hospital" | "city";

/**
 * Any analogy theme: one of the presets, or a free-text theme the user typed in themselves
 * (e.g. "Star Wars", "Cooking Show"). The `& {}` branch keeps editor autocomplete for the
 * presets while still accepting arbitrary strings — a bare `string` would lose the hints,
 * and a closed union would make custom themes impossible.
 */
export type AnalogyType = PresetAnalogyType | (string & {});

/** Runtime mirror of the preset themes — drives the AnalogySelector buttons (§2.2). */
export const ANALOGY_TYPES: readonly PresetAnalogyType[] = [
  "restaurant",
  "airport",
  "hospital",
  "city",
] as const;

/** PRD.md §2.5 — the theme auto-fired immediately after analyze success. */
export const DEFAULT_ANALOGY_TYPE: PresetAnalogyType = "restaurant";

/** Upper bound on a user-supplied theme string. Long enough for "90s Saturday Morning Cartoon". */
export const MAX_ANALOGY_TYPE_LENGTH = 40;

/** Narrowing helper — true only for the four built-in themes. */
export function isPresetAnalogyType(value: string): value is PresetAnalogyType {
  return ANALOGY_TYPES.indexOf(value as PresetAnalogyType) !== -1;
}

/**
 * Normalizes an untrusted analogyType off the wire into something safe to interpolate into a
 * prompt: trimmed, whitespace-collapsed, stripped of anything outside `[A-Za-z0-9 -]`, and
 * capped at MAX_ANALOGY_TYPE_LENGTH. Returns null when nothing usable survives.
 *
 * Both routes that accept an analogyType (and both prompts that embed it) rely on this being
 * the single gate — the theme string is free user text reaching an LLM, so it is sanitized
 * exactly like every other untrusted field.
 */
export function normalizeAnalogyType(raw: unknown): AnalogyType | null {
  if (typeof raw !== "string") return null;
  const cleaned = raw
    .replace(/[^A-Za-z0-9 -]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, MAX_ANALOGY_TYPE_LENGTH)
    .trim();
  return cleaned === "" ? null : cleaned;
}

/** One component→analogy vocabulary row (§2.2 mapping[]). */
export interface AnalogyMappingEntry {
  componentLabel: string;
  analogyRole: string;
  explanation: string;
}

/**
 * §2.2 labelMappings[] — the theme's short name for each diagram node, keyed by node id.
 *
 * Still part of the §2.2 response contract and still validated by /api/analogy, but no longer drawn
 * onto the diagram: the "Dynamic Diagram Label Morphing" mode that consumed it is retired
 * (ARCHITECTURE.md §5.1). The hover tooltip reads `mapping[].analogyRole` instead and touches no
 * SVG text (RULES.md §1).
 */
export interface LabelMapping {
  nodeId: string;
  /**
   * Prompt-generated free text, treated as untrusted: must pass the full RULES.md §1 pipeline
   * before being spliced into a diagram string. Missing ids fall back to the node's technical label.
   */
  analogyLabel: string;
}

export interface AnalogyRequest {
  architecture: ArchitectureNode[];
  analogyType: AnalogyType;
}

export interface AnalogyResult {
  analogyType: AnalogyType;
  mapping: AnalogyMappingEntry[];
  summary: string;
  /** Invariant: exactly one entry per id in the request's architecture[] (§2.2). */
  labelMappings: LabelMapping[];
}

export type AnalogyResponse = ApiResponse<AnalogyResult>;

