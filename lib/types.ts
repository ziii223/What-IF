/* ------------------------------------------------------------------ *
 * §4 — AnalysisPanel state (consumed by Phase 5.2's reducer)
 * ------------------------------------------------------------------ */

export type RequestStatus = "idle" | "loading" | "success" | "error";

export interface AnalogyState {
  status: RequestStatus;
  /** Currently selected theme — may differ from `data.analogyType` while a request is in flight. */
  type: AnalogyType | null;
  /** Last successful result; retained across a failed theme switch so the panel never blanks. */
  data: AnalogyResult | null;
}

export interface CrashState {
  status: RequestStatus;
  /** Most-recently-clicked node. Responses for any other id are discarded (last click wins, PRD.md §6). */
  pendingNodeId: string | null;
  /** Node the currently-rendered `result` belongs to; also the re-click-to-dismiss discriminator. */
  resultNodeId: string | null;
  result: CrashSimulationResult | null;
}

export interface AnalysisState {
  status: RequestStatus;
  repoSummary: RepoSummary | null;
  architecture: ArchitectureNode[];
  /**
   * The mermaid code on screen: the sanitized, repo-path-labelled string returned by /api/analyze.
   *
   * Set once per analysis and never rewritten. The former "Dynamic Diagram Label Morphing"
   * (ARCHITECTURE.md §5.1) that swapped these labels for analogy labels on ANALOGY_SUCCESS is
   * retired: the diagram now stays the repository's own structure, and a theme's mapping for a
   * folder is surfaced on hover instead (components/FlowchartView.tsx).
   */
  mermaidCode: string | null;
  /**
   * The same string as `mermaidCode`, held separately as the immutable, never-morphed baseline the
   * diagram was generated from. Kept so a future label-swapping mode has an untampered source to
   * rebuild from (ARCHITECTURE.md §5.1 point 1: always rebuild, never patch).
   */
  technicalMermaidCode: string | null;
  verdict: Verdict | null;
  /** Error surfaced by ErrorBanner via ERROR_MESSAGES; null when status is not "error". */
  error: ErrorCode | null;
  analogyState: AnalogyState;
  crashState: CrashState;
}

/** The 9 actions from ARCHITECTURE.md §4. CRASH_SIM_* may be stubbed until Phase 5.6b. */
export type AnalysisAction =
  | { type: "SUBMIT" }
  | {
      type: "ANALYZE_SUCCESS";
      payload: {
        repoSummary: RepoSummary;
        architecture: ArchitectureNode[];
        mermaidCode: string;
        verdict: Verdict | null;
      };
    }
  | { type: "ANALYZE_ERROR"; payload: { error: ErrorCode } }
  | { type: "ANALOGY_LOADING"; payload: { analogyType: AnalogyType } }
  | { type: "ANALOGY_SUCCESS"; payload: { data: AnalogyResult } }
  | { type: "ANALOGY_ERROR"; payload: { error: ErrorCode } }
  | { type: "CRASH_SIM_REQUEST"; payload: { nodeId: string } }
  | { type: "CRASH_SIM_SUCCESS"; payload: { nodeId: string; data: CrashSimulationResult } }
  | { type: "CRASH_SIM_ERROR"; payload: { nodeId: string; error: ErrorCode } };

