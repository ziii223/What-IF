/** Role vocabulary for architecture nodes (ARCHITECTURE.md §2.1). */
export type ArchitectureRole =
  | "frontend"
  | "api"
  | "database"
  | "queue"
  | "cache"
  | "worker"
  | "config"
  | "unknown";

/** Runtime mirror of ArchitectureRole — needed to validate untrusted LLM output (RULES.md §3). */
export const ARCHITECTURE_ROLES: readonly ArchitectureRole[] = [
  "frontend",
  "api",
  "database",
  "queue",
  "cache",
  "worker",
  "config",
  "unknown",
] as const;

/** One node of the generated architecture diagram (ARCHITECTURE.md §2.1). */
export interface ArchitectureNode {
  id: string;
  label: string;
  role: ArchitectureRole;
  evidence: string;
}

/**
 * Capped, LLM-ready digest of the target repo (ARCHITECTURE.md §1.3–§1.4).
 * Every field is subject to the size caps in §1.4 — the caps are enforced by the producers,
 * not by these types, but no field here may be widened to carry raw file blobs (BOB.md §3.3).
 */
export interface RepoSummary {
  name: string;
  description: string | null;
  language: string | null;
  /**
   * The repo's own source folders, depth 1–3 — `src`, `src/components`, `packages/web/src` —
   * ranked by descendant file count (ties alphabetical), capped at ≤24.
   *
   * This is the field the /api/analyze prompt draws its node labels from: the diagram is meant to
   * be the repository's actual structure, so the model may label a node only with one of these
   * paths and may never invent a module the digest does not show.
   */
  moduleFolders: string[];
  /** Top 10 extensions by count. */
  fileCountByExt: Record<string, number>;
  hasDocker: boolean;
  /** ≤15 service names (docker-compose only, regex-extracted). */
  services: string[];
  /** ≤20 package names combined, `dependencies` prioritised over `devDependencies`. */
  dependencies: string[];
  /** First 800 chars after image/badge stripping, or null if no README. */
  readmeExcerpt: string | null;
  /** True if the GitHub tree response reported `truncated: true` (§1.2 step 2). */
  truncated: boolean;
}

/* ------------------------------------------------------------------ *
 * §2.1 — Domain: verdict (optional enrichment)
 * ------------------------------------------------------------------ */

export type FrictionLevel = "low" | "moderate" | "high";

export const FRICTION_LEVELS: readonly FrictionLevel[] = [
  "low",
  "moderate",
  "high",
] as const;

/**
 * Optional badge generated by the same LLM call as mermaidCode/architecture (§2.1).
 * Consumers MUST treat a missing value, or a `friction` outside FrictionLevel, as `null`
 * and render no badge — never as a `parse_failed` for the whole response (§2.1, Phase 2.6).
 */
export interface Verdict {
  friction: FrictionLevel;
  /** Badge caption, capped at ~160 chars server-side. Grounded only in the same RepoSummary (§2.1). */
  reason: string;
}

/* ------------------------------------------------------------------ *
 * §3 — Error codes
 * ------------------------------------------------------------------ */

export type ErrorCode =
  | "invalid_url"
  | "not_found"
  | "rate_limited"
  | "parse_failed"
  | "timeout"
  | "unknown";

/** §3 — client maps each code to exactly one user-facing string. Never forward raw upstream bodies. */
export const ERROR_MESSAGES: Record<ErrorCode, string> = {
  invalid_url: "That doesn't look like a valid GitHub repo URL.",
  not_found: "Repo not found — check the URL or make sure it's public.",
  rate_limited: "GitHub rate limit hit — wait a minute and try again.",
  parse_failed: "Something went wrong reading that repo's structure. Try again.",
  timeout: "That took too long — the repo might be very large. Try again.",
  unknown: "Something went wrong. Try again.",
};

/** Error codes reachable from the two GitHub-free routes (§2.2, §2.3). */
export type LlmErrorCode = Extract<ErrorCode, "parse_failed" | "timeout" | "unknown">;

/* ------------------------------------------------------------------ *
 * §2 — Transport envelope
 * ------------------------------------------------------------------ */

export type ApiSuccess<T> = { data: T; error?: undefined };
export type ApiFailure = { data?: undefined; error: ErrorCode };
export type ApiFailureLlm = { data?: undefined; error: LlmErrorCode };

/**
 * All routes respond `{ data }` on success, `{ error }` on failure (§2.1–§2.3).
 * The optional-`undefined` form keeps `if (res.error) ... else res.data` narrowing safe under strict mode.
 */
export type ApiResponse<T> = ApiSuccess<T> | ApiFailure;

